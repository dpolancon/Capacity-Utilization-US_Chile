# ---------------------------------------------------------------------------
# fixedb_crit(): interpolated fixed-b critical value lookup
# ---------------------------------------------------------------------------
# stat  : "t" (single-coefficient upper-tail test) or "wald" (joint test of
#         all k stochastic regressors' lambda2 = 0, i.e. this repo's VW Type 2
#         statistic).
# k     : number of stochastic (I(1)) regressors in the cointegrating
#         regression (integer, 1-4 currently tabulated).
# b     : bandwidth-ratio b = bandwidth / T for the fitted model. Values
#         outside [0.02, 1.00] are clamped to the nearest tabulated boundary
#         (extrapolation beyond the tabulated range is not attempted).
# level : one of 0.10, 0.05, 0.01 (two-tailed significance level).
#
# Returns a single interpolated critical value (linear interpolation over the
# b grid). Direction of the significance test (>= for Wald/Shin-style tests
# testing H0: no effect via a large positive statistic; <= for tests like
# EG-ADF whose rejection region is in the left tail) is NOT handled here --
# callers apply their own comparison direction to the returned critical value.
fixedb_crit <- function(stat = c("t", "wald"), k, b, level = 0.10) {
  stat <- match.arg(stat)

  if (is.null(k) || is.na(k) || k < 1) {
    stop("fixedb_crit: k must be a positive integer (number of stochastic regressors)")
  }
  k_int <- as.integer(round(k))
  tables <- if (stat == "t") .fixedb_ttest_tables else .fixedb_wald_tables
  k_max <- length(tables)
  if (k_int > k_max) {
    stop(sprintf(
      "fixedb_crit: k=%d exceeds the tabulated range (1..%d) for stat='%s'. ",
      k_int, k_max, stat
    ), "Digitize the additional Vogelsang-Wagner (2014) table before using k > ", k_max, ".")
  }
  if (k_int < 1) k_int <- 1

  tab <- tables[[as.character(k_int)]]
  pcol <- switch(
    as.character(level),
    `0.1`  = "p90",
    `0.10` = "p90",
    `0.05` = "p95",
    `0.01` = "p99",
    stop("fixedb_crit: level must be one of 0.10, 0.05, 0.01")
  )
  crit_vec <- tab[[pcol]]

  b_clamped <- min(max(b, min(.fixedb_b_grid)), max(.fixedb_b_grid))
  as.numeric(stats::approx(x = .fixedb_b_grid, y = crit_vec, xout = b_clamped, rule = 2)$y)
}

# ---------------------------------------------------------------------------
# fixedb_stars(): convenience wrapper returning a LaTeX star string
# ---------------------------------------------------------------------------
# direction: "ge" if rejection occurs for stat >= critical value (Wald,
#            Shin-LM-style tests), "le" if rejection occurs for stat <=
#            critical value (EG-ADF-style left-tail tests).
fixedb_stars <- function(stat_val, stat = c("t", "wald"), k, b, direction = c("ge", "le")) {
  stat <- match.arg(stat)
  direction <- match.arg(direction)
  if (is.null(stat_val) || length(stat_val) == 0 || is.na(stat_val)) return("")

  cmp <- if (direction == "ge") {
    function(x, crit) x >= crit
  } else {
    function(x, crit) x <= crit
  }

  c01 <- fixedb_crit(stat, k, b, level = 0.01)
  c05 <- fixedb_crit(stat, k, b, level = 0.05)
  c10 <- fixedb_crit(stat, k, b, level = 0.10)

  if (cmp(stat_val, c01)) return("$^{***}$")
  if (cmp(stat_val, c05)) return("$^{**}$")
  if (cmp(stat_val, c10)) return("$^{*}$")
  ""
}
