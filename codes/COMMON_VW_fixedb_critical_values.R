# Fixed-b critical value tables for IM-OLS inference (Vogelsang & Wagner, 2014,
# "Integrated Modified OLS Estimation and Fixed-b Inference for Cointegrating
# Regressions", Journal of Econometrics 178(2), 741-760).
#
# Source: Vogelsang & Wagner online supplement "Tables with Critical Values for
# Integrated Modified OLS Estimation and Fixed-b Inference for Cointegrating
# Regressions" (https://www.aau.at/wp-content/uploads/2020/04/2014-Vogelsang-Wagner-IM-OLS.pdf),
# Section 1 (Bartlett Kernel, Intercept Only) -- matches this repo's deter matrix
# (intercept + step-shift dummies, no linear trend).
#
# Two families of tables, each indexed by k = number of stochastic (I(1))
# regressors in the cointegrating regression (k_cap, interaction terms, NetC
# share, etc. -- NOT counting the intercept or step dummies):
#
#   - t-test tables (Tables 1-4 in the supplement): critical values for a single
#     coefficient t-statistic, upper tail. Two-tailed significance levels map to
#     these one-tailed percentiles: p<0.10 -> 95th pct, p<0.05 -> 97.5th pct,
#     p<0.01 -> 99.5th pct.
#   - Wald tables (Tables 5, 7, 10, 14 in the supplement -- the "diagonal" cases
#     where all k stochastic regressors are jointly tested, matching how this
#     repo's VW Type 2 test is constructed): p<0.10 -> 90th pct, p<0.05 -> 95th
#     pct, p<0.01 -> 99th pct.
#
# All tables are tabulated over a common bandwidth-ratio grid b = bandwidth/T,
# b in {0.02, 0.04, ..., 1.00}. Critical values are NOT constant in b -- this is
# the defining feature of fixed-b asymptotics (Kiefer & Vogelsang 2002, 2005):
# the bandwidth is held as a fixed fraction of the sample size rather than let
# to vanish asymptotically, so the reference distribution is b-dependent.
#
# Only k = 1..4 are tabulated here (the maximum this repo currently needs, see
# E17_Cointegration_Significance_Stars_Lock.md). If a future specification needs
# k > 4 stochastic regressors (e.g. an expanded Section 3.2 model), the source
# PDF above tabulates up to at least k = 10 for the Wald case; digitize the
# additional table(s) into `.fixedb_wald_tables` / `.fixedb_ttest_tables` below
# following the same structure -- do not extrapolate across k.
# ---------------------------------------------------------------------------

